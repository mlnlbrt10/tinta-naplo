                      ],
                    ),
                    const SizedBox(height: 4),
                    Text(
                      [
                        grade.type.description,
                        if (modeText != null && modeText.isNotEmpty) modeText,
                      ].join(' • '),
                      style: theme.textTheme.bodySmall?.copyWith(
                        color: scheme.primary,
                        fontWeight: FontWeight.w600,
                      ),
                    ),
