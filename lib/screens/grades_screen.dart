    final currentRounded = _prefs.evaluateSubjectRoundedGrade(
      avg,
      widget.summary.heroId,
      widget.summary.subjectName,
    );
    _targetGrade = (currentRounded < 5) ? (currentRounded + 1) : 5;
  }

  @override
